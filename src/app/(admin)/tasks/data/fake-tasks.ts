/** Temporary fake tasks around the current week until the tasks API exists. */
export function createFakeTasks(): Task[] {
  const monday = startOfWeek(dayjs());
  return SEEDS.map((seed, index) => {
    const [hour, minute] = seed.start.split(":").map(Number);
    const start = monday.add(seed.day, "day").hour(hour).minute(minute);
    return {
      Id: `task-${index + 1}`,
      Title: seed.title,
      Description: seed.description ?? null,
      Status: seed.status,
      Priority: seed.priority,
      Category: seed.category,
      Assignee: TASK_ASSIGNEES[seed.person],
      StartAt: start.toISOString(),
      EndAt: start.add(seed.minutes, "minute").toISOString(),
      Location: seed.location ?? null,
      Tags: seed.tags ?? [],
    };
  });
}
